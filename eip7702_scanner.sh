echo -e "${BLUE}╔════════════════════════════════════════════════════╗${NC}"
echo -e "${BLUE}║              Quick Statistics                      ║${NC}"
echo -e "${BLUE}╠════════════════════════════════════════════════════╣${NC}"
printf "${BLUE}║${NC} %-30s ${GREEN}%18s ${BLUE}║${NC}\n" "Mainnets Supporting EIP-7702:" "${#SUPPORTED_MAINNETS[@]}"
printf "${BLUE}║${NC} %-30s ${YELLOW}%18s ${BLUE}║${NC}\n" "Testnets Supporting EIP-7702:" "${#SUPPORTED_TESTNETS[@]}"
printf "${BLUE}║${NC} %-30s ${GREEN}%18s ${BLUE}║${NC}\n" "Total Supported:" "$SUPPORTED_CHAINS"
echo -e "${BLUE}╚════════════════════════════════════════════════════╝${NC}"
echo ""

# Show some example networks
if [ ${#SUPPORTED_MAINNETS[@]} -gt 0 ]; then
    echo -e "${BLUE}🌐 Sample Supported Mainnets:${NC}"
    count=0
    for entry in "${SUPPORTED_MAINNETS[@]}"; do
        IFS='|' read -r name id rpc <<< "$entry"
        echo -e "  ${GREEN}•${NC} $name (ID: $id)"
        count=$((count + 1))
        [ $count -ge 5 ] && break
    done
    [ ${#SUPPORTED_MAINNETS[@]} -gt 5 ] && echo -e "  ${BLUE}... and $((${#SUPPORTED_MAINNETS[@]} - 5)) more${NC}"
    echo ""
fi

